-- =====================================================================
-- RedFit — Modelagem de Banco de Dados — Script base (MySQL 8.0.16 ou superior)
-- REQUER MySQL >= 8.0.16: nas versões 8.0.0–8.0.15 as cláusulas CHECK são aceitas
-- na sintaxe, mas IGNORADAS (não são aplicadas). Confira com: SELECT VERSION();
-- Não é compatível com MariaDB (a collation utf8mb4_0900_ai_ci só existe no MySQL 8).
-- Gerado a partir do Relatório Técnico (Entrega 2).
-- Já inclui as regras atualizadas das PENDÊNCIAS:
--   * PLANO com valor promocional do 1º mês, meses de fidelidade,
--     % de multa, qtd. de amigos e renovação automática
--   * CHECK_IN.TP_ACESSO: DIGITAL, FACIAL, APP_PARCEIRO
--   * Sem boleto (formas: PIX, DEBITO, CREDITO)
--   * Funcionários com endereço; instrutor com dados de formação
--   * TREINO registra quem alterou por último
-- v2: colunas de auditoria (DT_CRIACAO/DT_ATUALIZACAO) e índices extras.
-- Procure por "EDITAR" para os pontos que o grupo ainda precisa decidir.
-- =====================================================================

DROP DATABASE IF EXISTS redfit;
CREATE DATABASE redfit CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
USE redfit;

-- ---------------------------------------------------------------------
-- 1. UNIDADE
-- ---------------------------------------------------------------------
CREATE TABLE UNIDADE (
  ID_UNIDADE      INT AUTO_INCREMENT PRIMARY KEY,
  NM_UNIDADE      VARCHAR(100) NOT NULL,
  DS_LOGRADOURO   VARCHAR(150) NOT NULL,
  NR_ENDERECO     VARCHAR(10)  NOT NULL,
  DS_COMPLEMENTO  VARCHAR(60)  NULL,
  NM_BAIRRO       VARCHAR(80)  NOT NULL,
  NR_CEP          CHAR(8)      NOT NULL,
  NM_CIDADE       VARCHAR(80)  NOT NULL,
  SG_UF           CHAR(2)      NOT NULL,
  DT_CRIACAO      DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  DT_ATUALIZACAO  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT CK_UNIDADE_CEP CHECK (NR_CEP REGEXP '^[0-9]{8}$')
);

-- ---------------------------------------------------------------------
-- 2. FUNCIONÁRIOS (sem generalização — decisão do grupo)
-- ---------------------------------------------------------------------
CREATE TABLE GERENTE (
  ID_GERENTE      INT AUTO_INCREMENT PRIMARY KEY,
  NM_GERENTE      VARCHAR(120) NOT NULL,
  NR_CPF          CHAR(11)     NOT NULL UNIQUE,
  NR_TELEFONE     VARCHAR(11)  NOT NULL,
  DS_EMAIL        VARCHAR(120) NULL,
