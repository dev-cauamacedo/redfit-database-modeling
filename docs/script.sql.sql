CREATE TABLE CHECK_IN (
  ID_CHECK_IN   BIGINT AUTO_INCREMENT PRIMARY KEY,
  ID_ALUNO      INT          NOT NULL,
  ID_UNIDADE    INT          NOT NULL,
  DT_HR_ACESSO  DATETIME     NOT NULL,
  TP_ACESSO     VARCHAR(15)  NOT NULL,
  ST_ACESSO     VARCHAR(10)  NOT NULL,
  DS_MOTIVO_NEGADO VARCHAR(100) NULL,
  DT_CRIACAO      DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  DT_ATUALIZACAO  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT CK_CI_TIPO   CHECK (TP_ACESSO IN ('DIGITAL','FACIAL','APP_PARCEIRO')),
  CONSTRAINT CK_CI_STATUS CHECK (ST_ACESSO IN ('LIBERADO','NEGADO')),
  CONSTRAINT CK_CI_MOTIVO CHECK ((ST_ACESSO = 'NEGADO' AND DS_MOTIVO_NEGADO IS NOT NULL)
                              OR (ST_ACESSO = 'LIBERADO' AND DS_MOTIVO_NEGADO IS NULL)),
  CONSTRAINT FK_CI_ALUNO FOREIGN KEY (ID_ALUNO)
    REFERENCES ALUNO (ID_ALUNO) ON DELETE RESTRICT,
  CONSTRAINT FK_CI_UNIDADE FOREIGN KEY (ID_UNIDADE)
    REFERENCES UNIDADE (ID_UNIDADE) ON DELETE RESTRICT
);
CREATE INDEX IX_CI_DATA ON CHECK_IN (ID_UNIDADE, DT_HR_ACESSO);

