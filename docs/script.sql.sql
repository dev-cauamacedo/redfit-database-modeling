CREATE TABLE PLANO (
  ID_PLANO             INT AUTO_INCREMENT PRIMARY KEY,
  NM_PLANO             VARCHAR(50)   NOT NULL UNIQUE,
  DS_ABRANGENCIA       VARCHAR(100)  NOT NULL,
  VL_MENSAL            DECIMAL(10,2) NOT NULL,
  VL_PRIMEIRO_MES      DECIMAL(10,2) NULL,      -- promocional (RED R$ 9,90)
  VL_MATRICULA         DECIMAL(10,2) NOT NULL DEFAULT 0,
  IN_FIDELIDADE        TINYINT(1)    NOT NULL DEFAULT 0,
  QT_MESES_FIDELIDADE  TINYINT       NOT NULL DEFAULT 0,
  PC_MULTA             DECIMAL(5,2)  NULL,      -- FIT 20%; Anual = mensalidades restantes
  QT_AMIGOS            TINYINT       NOT NULL DEFAULT 0,
  IN_RENOVACAO_AUTO    TINYINT(1)    NOT NULL DEFAULT 1,
  IN_BLOQUEIA_ATRASO   TINYINT(1)    NOT NULL DEFAULT 0, -- RN16: só RED bloqueia
  DS_PLANO             VARCHAR(255)  NULL,
  IN_ATIVO             TINYINT(1)    NOT NULL DEFAULT 1,
  DT_CRIACAO      DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  DT_ATUALIZACAO  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT CK_PLANO_VALORES CHECK (VL_MENSAL > 0 AND VL_MATRICULA >= 0),
  CONSTRAINT CK_PLANO_FIDEL   CHECK (IN_FIDELIDADE IN (0,1)
                                     AND (IN_FIDELIDADE = 1 OR QT_MESES_FIDELIDADE = 0)),
  CONSTRAINT CK_PLANO_MULTA   CHECK (PC_MULTA IS NULL OR PC_MULTA BETWEEN 0 AND 100)
);

